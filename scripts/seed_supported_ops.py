"""Convert onnx-tensorrt docs/operators.md into configs/supported_ops.yaml.

Usage:
    curl -sfL https://raw.githubusercontent.com/onnx/onnx-tensorrt/<commit>/docs/operators.md \
        -o operators.md
    python scripts/seed_supported_ops.py operators.md <commit> <YYYY-MM-DD> \
        > configs/supported_ops.yaml

The result is provisional: C4 validates it against the real TensorRT parser.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml


def parse(text: str) -> tuple[str, int, int, dict[str, dict], list[str]]:
    m = re.search(r"TensorRT ([\d.]+) supports operators in the inclusive range of opset (\d+) "
                  r"to opset (\d+)", text)  # fmt: skip
    if not m:
        raise ValueError("version/opset sentence not found; the document format changed")
    supported: dict[str, dict] = {}
    unsupported: list[str] = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or cells[1] not in ("Y", "N") or cells[0] == "Operator":
            continue
        op, flag = cells[0], cells[1]
        if flag == "N":
            unsupported.append(op)
            continue
        entry: dict = {"types": [t.strip() for t in cells[2].split(",") if t.strip()]}
        restrictions = cells[3] if len(cells) > 3 else ""
        restrictions = re.sub(r"<br\s*/?>", " ", restrictions).replace("`", "").strip()
        if restrictions:
            entry["restrictions"] = re.sub(r"\s+", " ", restrictions)
        supported[op] = entry
    return m.group(1), int(m.group(2)), int(m.group(3)), supported, unsupported


def main() -> int:
    path, commit, retrieved = sys.argv[1], sys.argv[2], sys.argv[3]
    trt, lo, hi, supported, unsupported = parse(Path(path).read_text())
    header = (
        "# ONNX ops accepted by the TensorRT ONNX parser. Generated by\n"
        "# scripts/seed_supported_ops.py from onnx-tensorrt docs/operators.md.\n"
        "# PROVISIONAL until C4 validates it against the real parser of the pinned TensorRT.\n"
    )
    doc = {
        "source": f"https://github.com/onnx/onnx-tensorrt/blob/{commit}/docs/operators.md",
        "source_commit": commit,
        "retrieved": retrieved,
        "tensorrt_version": trt,
        "status": "provisional",
        "opset": {"min": lo, "max": hi},
        "ops": supported,
        "unsupported": sorted(unsupported),
    }
    sys.stdout.write(header + yaml.safe_dump(doc, sort_keys=False, width=100))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
